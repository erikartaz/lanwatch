def normalize_mac(mac: str) -> Optional[str]:
    """Clean and standardize MAC address to XX:XX:XX:XX:XX:XX format."""
    if not mac:
        return None
    cleaned = re.sub(r"[^0-9A-Fa-f]", "", mac).upper()
    if len(cleaned) != 12:
        return None
    return ":".join(cleaned[i:i+2] for i in range(0, 12, 2))


def lookup_vendor(mac: str) -> str:
    """Resolve hardware manufacturer from MAC address OUI prefix."""
    normalized = normalize_mac(mac)
    if not normalized:
        return "Unknown"

    # Check first 3 octets
    prefix = normalized[:8]
    if prefix in OUI_DATABASE:
        return OUI_DATABASE[prefix]

    # Check for locally administered address (randomized MAC used by iOS/Android)
    # If second least significant bit of first byte is 1 (e.g. x2, x6, xA, xE)
    first_byte = int(normalized[:2], 16)
    if first_byte & 0x02:
        return "Dispositivo Mobile (MAC Casuale / Privacy)"

    return "Produttore Sconosciuto"


